function isPubliclyVisible(product: MockProduct) {
  return product.status === "ACTIVE" || product.status === "OUT_OF_STOCK";
}

export function getVisibleProducts() {
  return products.filter(isPubliclyVisible);
}

export function getBestSellerProducts() {
  return getVisibleProducts().filter((p) => p.isBestSeller);
}

export function getProductsByCategory(categorySlug: string) {
  return getVisibleProducts().filter((p) => p.categorySlug === categorySlug);
}

export function getProductsByShop(shopSlug: string) {
  return getVisibleProducts().filter((p) => p.shopSlug === shopSlug);
}

// Unfiltered — includes drafts/archived/out-of-stock. For vendor-facing
// management views only; never render this on a public page.
export function getVendorProducts(shopSlug: string) {
  return products.filter((p) => p.shopSlug === shopSlug);
}

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getRelatedProducts(product: MockProduct, limit = 4) {
  return getVisibleProducts()
    .filter((p) => p.categorySlug === product.categorySlug && p.id !== product.id)
    .slice(0, limit);
}
